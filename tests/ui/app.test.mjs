let serial = 0, buffer = '', sessionId, browserError = '';
const requests = new Map();
const errors = [];
browser.stderr.on('data', data => { browserError = (browserError + data.toString()).slice(-2000); });
browser.on('error', error => { console.error(error.message); });
browser.stdio[4].on('data', data => {
  buffer += data.toString();
  let separator;
  while ((separator = buffer.indexOf('\0')) >= 0) {
    const packet = buffer.slice(0, separator); buffer = buffer.slice(separator + 1);
    if (!packet) continue;
    const message = JSON.parse(packet);
    if (message.method === 'Runtime.exceptionThrown') errors.push(message.params.exceptionDetails.text + ': ' + (message.params.exceptionDetails.exception?.description ?? ''));
    if (message.method === 'Log.entryAdded' && message.params.entry.level === 'error') errors.push(message.params.entry.text);
    const request = requests.get(message.id);
    if (request) { requests.delete(message.id); clearTimeout(request.timer); message.error ? request.reject(new Error(JSON.stringify(message.error))) : request.resolve(message.result); }
  }
});
function cdp(method, params = {}, page = true) {
  return new Promise((resolveResult, reject) => {
    const id = ++serial;
    const timer = setTimeout(() => { requests.delete(id); reject(new Error(`Tempo esgotado: ${method}. ${browserError}`)); }, 20000);
    requests.set(id, { resolve: resolveResult, reject, timer });
    browser.stdio[3].write(JSON.stringify({ id, method, params, ...(page && sessionId ? { sessionId } : {}) }) + '\0');
  });
}
