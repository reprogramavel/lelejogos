import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import nspell from 'nspell';
import dictionary from 'dictionary-pt';
import { projectPath } from './lib/build-options.mjs';

const sources = [
  'vendor/dictionary-pt/index.dic', 'vendor/dictionary-pt/index.aff',
  'vendor/pt-br/lexico', 'vendor/pt-br/conjugacoes',
];
const sourceHashes = {};
for (const path of sources) sourceHashes[path] = createHash('sha256').update(await readFile(projectPath(path))).digest('hex');
const normalize = word => word.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase();
// Original case matters: reject proper names/acronyms before removing accents.
const fiveLetters = word => /^[a-záàâãéêíóôõúüç]{5}$/.test(word.normalize('NFC'));
console.log('Expandindo o dicionário português com nspell (somente na geração)…');
const spell = nspell(dictionary.aff);
if (spell.compoundRules.length) throw new Error('Esta exportação por lotes exige um dicionário sem regras de composição.');
const words = new Set();
const originalWords = new Set();
const forbidden = new Set();
const entries = dictionary.dic.toString('utf8').split(/\r?\n/).slice(1).filter(Boolean);
// Bound memory: expand a batch, retain five-letter forms and discard other forms.
for (let offset = 0; offset < entries.length; offset += 2000) {
  const batch = entries.slice(offset, offset + 2000);
  spell.data = Object.create(null);
  spell.dictionary(batch.length + '\n' + batch.join('\n') + '\n');
  for (const word in spell.data) {
    if (!fiveLetters(word)) continue;
    if (spell.data[word].includes(spell.flags.FORBIDDENWORD)) forbidden.add(word);
    else if (spell.correct(word)) originalWords.add(word);
  }
  if (offset % 40000 === 0) console.log(`Entradas processadas: ${Math.min(offset + batch.length, entries.length)} / ${entries.length}`);
}
for (const word of originalWords) if (!forbidden.has(word)) words.add(normalize(word));
const dictionaryCount = words.size;
const fserbWords = new Set();
for (const path of sources.slice(2)) {
  for (const word of (await readFile(projectPath(path), 'utf8')).split(/\r?\n/)) {
    if (fiveLetters(word) && !forbidden.has(word)) { const normalized = normalize(word); fserbWords.add(normalized); words.add(normalized); }
  }
}
// Spell checkers also accept technical abbreviations that aren't word-game guesses.
const excludedAbbreviations = ['ASCII', 'HTTPS'];
const sorted = [...words].filter(word => !excludedAbbreviations.includes(word)).sort();
const rows = [];
for (let i = 0; i < sorted.length; i += 16) rows.push(sorted.slice(i, i + 16).join(' '));
const header = '// Generated by npm run vocabulary:generate. Do not edit manually.\n' +
  '// Sources: dictionary-pt 4.0.0 / VERO (MPL-2.0) and fserb/pt-br (MIT).\n' +
  '// See vendor/README.md for authors, pinned revisions, licenses and regeneration.\n';
await writeFile(projectPath('src/features/termo/external-words.ts'), header + 'export const externalWords = `\n' + rows.join('\n') + '\n`.trim().split(/\\s+/);\n');
const { allowedWords, answerWords } = await import('../src/features/termo/words.ts');
const stats = { dictionaryProcessedEntries: entries.length, dictionaryFiveLetterWords: dictionaryCount,
  fserbFiveLetterWords: fserbWords.size, combinedFiveLetterWords: sorted.length,
  totalAcceptedWords: allowedWords.size, possibleAnswers: answerWords.length, excludedAbbreviations, sourceHashes };
await writeFile(projectPath('src/features/termo/external-words.stats.json'), JSON.stringify(stats, null, 2) + '\n');
console.log(JSON.stringify(stats, null, 2));
